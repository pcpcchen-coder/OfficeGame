export interface BotDef {
  id: string;
  level: number;
  name: string;
  title: string;
  secretLabel: string;
  /** 說溜嘴時講出的秘密 */
  secret: string;
  /** 防線初始值；降到 0 以下自動說溜嘴 */
  defense: number;
  /** 防線在這個值以下時直接問，就會說出秘密 */
  askBelow: number;
  /** 直接問秘密時的關鍵字 */
  askWords: string[];
  /** 各策略讓防線降低多少（負數 = 防線反而升高） */
  weights: Partial<Record<Tactic, number>>;
  /** 稱讚超過一次就反感 */
  hatesRepeatedPraise?: boolean;
  /** 同一招重複使用時的效果倍率（預設 0.5，越大越不會膩） */
  decay?: number;
  intro: string[];
  /** 各策略的回應；正面與負面共用同一組 */
  lines: Partial<Record<Tactic, string[]>>;
  neutral: string[];
  refuse: string[];
  reveal: string;
  hints: string[];
}

